    label = LABELS[row["tweet_id"]]

    df.at[i, "human_intent"] = label["intent"]
    df.at[i, "human_notes"] = label.get("notes", "")
    df.at[i, "is_ambiguous"] = label.get("ambiguous", False)
    df.at[i, "needs_context"] = label.get("needs_context", False)

